<p class="lead">
  BUOY.fish is now live in the Gulf of Nicoya, Costa Rica: our first deployment
  in Central America, bringing connected fishing gear tracking to the Gulf's
  artisanal fisheries in partnership with the Global Ghost Gear Initiative.
</p>

<h3>The Gulf of Nicoya</h3>

<p>
  The Gulf of Nicoya is one of Costa Rica's most important fishing grounds,
  supporting thousands of artisanal fishermen and their communities. It's also a
  complex, vast body of water where gear loss is a persistent problem — and
  where the environmental consequences of ghost gear compound in a region rich
  with marine biodiversity.
</p>

<h3>What We Built</h3>

<p>
  The project went live on July 24, 2026. Over the following eight days our team
  installed five LoRaWAN gateways at sites around the Gulf, hosted by local
  businesses and landowners who agreed to give our equipment a home. Those
  gateways are the wireless backbone the trackers report through.
</p>

<p>
  On the water, the deployment runs 28 smart buoys and 14 vessel trackers. That
  is more than the 20 buoys and 10 trackers we originally planned.
</p>

