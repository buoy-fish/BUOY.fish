<h3>Applying What We've Learned</h3>

<p>
  Every deployment teaches us something that shapes the next one. The Costa Rica
  project was designed around key lessons from our
  <a href="/blog/punta-abreojos-deployment">Punta Abreojos</a> and
  <a href="/blog/nova-scotia-trial">Nova Scotia</a> deployments:
</p>

<ul>
  <li>
    <strong>Height and line-of-sight are paramount.</strong> In Nova Scotia, low-lying
    port facilities underperformed due to "land shadows," while elevated sites provided
    far better coverage. In Costa Rica we prioritized high, open sites with a clear
    view across the Gulf.
  </li>
  <li>
    <strong>Local relationships are everything.</strong> Securing installation sites
    requires trust and embedded local partners. GGGI and local partners brokered
    introductions and permissions before our team arrived, which is how five gateways
    went up in a little over a week.
  </li>
</ul>

<h3>Why Costa Rica</h3>

<p>
  Expanding to Central America is a strategic milestone for BUOY.fish. It shows
  the technology can adapt to different geographies, fishery types, and
  operational contexts. The Gulf of Nicoya's artisanal fisheries operate
  differently from Baja's cooperative lobster fleet or Nova Scotia's regulated
  lobster zones — and understanding those differences is how we build a product
  that works for fishing communities everywhere.
</p>

